const { createRequire } = require('node:module');
const req = createRequire('/Users/frangoncalves/Desktop/DEV/heremita/apps/web/package.json');
const { chromium, devices } = req('@playwright/test');
const BASE = 'http://localhost:3100';
const ALERT = '[role=alert]:not(next-route-announcer)';
(async () => {
  const browser = await chromium.launch();
  const context = await browser.newContext({ ...devices['Pixel 7'], viewport: { width: 360, height: 740 } });
  const page = await context.newPage();
  const problems = [];
  page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') problems.push(m.type() + ': ' + m.text().slice(0, 400)); });
  page.on('pageerror', (e) => problems.push('pageerror ' + e.message));
  await page.exposeFunction('reportCsp', (v) => problems.push('CSP ' + v));
  await page.addInitScript(() => document.addEventListener('securitypolicyviolation', (e) => window.reportCsp(e.violatedDirective + ' ' + e.blockedURI)));
  const log = (...a) => console.log(...a);
  try {
    await page.goto(BASE + '/pt-BR/t22-probe?day=ideas');
    log('gate signed out ->', page.url());
    const email = `t22b-${Date.now()}@example.com`;
    await page.locator('main').getByRole('link', { name: 'Criar conta' }).click();
    await page.waitForURL(/signup/);
    log('signup url (next kept)', page.url());
    await page.getByRole('textbox', { name: 'Nome' }).fill('Beatriz Probe Long Name');
    await page.getByRole('textbox', { name: 'E-mail' }).fill(email);
    await page.getByLabel('Senha', { exact: true }).fill('passphrase for probing');
    await page.getByRole('button', { name: 'Criar conta' }).click();
    await page.waitForURL((u) => u.pathname === '/pt-BR/t22-probe');
    log('after signup ->', page.url());
    log('scrollWidth@360', await page.evaluate(() => document.documentElement.scrollWidth));
    await page.screenshot({ path: 'probe-360.png' });
    await page.getByRole('button', { name: /Conta: Beatriz/ }).click();
    await page.getByRole('button', { name: 'Sair' }).click();
    await page.waitForURL(BASE + '/pt-BR');
    log('after logout', page.url());
    await page.goto(BASE + '/pt-BR/signup');
    await page.getByRole('textbox', { name: 'Nome' }).fill('X');
    await page.getByRole('textbox', { name: 'E-mail' }).fill(email);
    await page.getByLabel('Senha', { exact: true }).fill('passphrase for probing');
    await page.getByRole('button', { name: 'Criar conta' }).click();
    await page.locator(ALERT).first().waitFor();
    log('dup alert', await page.locator(ALERT).first().textContent());
    await page.goto(BASE + '/en/login');
    await page.getByRole('textbox', { name: 'E-mail' }).fill(email);
    await page.getByLabel('Password', { exact: true }).fill('wrong password!');
    await page.getByRole('button', { name: 'Log in' }).click();
    await page.locator(ALERT).first().waitFor();
    log('wrong pw alert', await page.locator(ALERT).first().textContent());
    await page.goto(BASE + '/en/signup');
    await page.getByRole('textbox', { name: 'Name' }).fill('X');
    await page.getByRole('textbox', { name: 'E-mail' }).fill(`common-${Date.now()}@example.com`);
    await page.getByLabel('Password', { exact: true }).fill('123456789012');
    await page.getByRole('button', { name: 'Create account' }).click();
    await page.locator(ALERT).first().waitFor();
    log('common pw alert', await page.locator(ALERT).first().textContent());
  } catch (e) { log('ERR', e.message.split('\n')[0]); }
  log('problems', JSON.stringify(problems, null, 1));
  await browser.close();
})();
